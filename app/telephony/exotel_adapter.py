import asyncio
import base64
import json
import time
from typing import Callable, Coroutine, Dict, Optional
from app.core.logging import logger
from app.telephony.codecs import (
    PCM_BYTES_PER_FRAME,
    ULAW_BYTES_PER_FRAME,
    calculate_rms,
    pcm_to_ulaw,
    ulaw_to_pcm,
)


class ExotelOutboundPacer:
    """
    Outbound audio pacer tailored specifically for Exotel AgentStream.
    Exotel media requires 8 kHz, mono 16-bit linear PCM (320 bytes per 20ms frame).

    Converts internal 8kHz G.711 μ-law audio generated by ElevenLabs TTS into
    linear16 PCM, paces delivery at 50Hz (~20ms per packet), tracks Exotel mark
    events, and handles sub-200ms barge-in by flushing the queue and dispatching
    an Exotel 'clear' event.
    """

    def __init__(
        self,
        stream_sid: str,
        send_fn: Callable[[str], Coroutine],
        frame_interval_sec: float = 0.02,
        mark_interval_frames: int = 15,  # Insert mark event every 300ms
        on_playback_complete: Optional[Callable[[], None]] = None,
    ):
        self.stream_sid = stream_sid
        self.send_fn = send_fn
        self.frame_interval_sec = frame_interval_sec
        self.mark_interval_frames = mark_interval_frames
        self.on_playback_complete = on_playback_complete

        self._queue: asyncio.Queue[Optional[dict]] = asyncio.Queue()
        self._pacer_task: Optional[asyncio.Task] = None
        self._running = False

        # Mark tracking
        self._mark_counter = 0
        self._sent_marks: Dict[str, dict] = {}  # mark_name -> metadata
        self._last_acked_mark: Optional[str] = None
        self._last_acked_metadata: Optional[dict] = None
        self._frames_since_mark = 0
        self._turn_final_mark_sent = False
        self._active_turn_id = 1
        self._last_audio_metadata: Optional[dict] = None

    def start(self):
        """Start the background pacing loop."""
        if not self._running:
            self._running = True
            self._pacer_task = asyncio.create_task(self._pacing_loop())
            logger.info(f"ExotelOutboundPacer started for stream: {self.stream_sid}")

    def start_turn(self) -> int:
        """Explicitly begins a new assistant turn, advancing turn generation."""
        self._active_turn_id += 1
        self._turn_final_mark_sent = False
        return self._active_turn_id

    def mark_turn_end(self, turn_id: Optional[int] = None):
        """Signals that all audio chunks for the current assistant turn have been enqueued."""
        tid = self._active_turn_id if turn_id is None else turn_id
        self._queue.put_nowait({
            "type": "turn_end",
            "turn_id": tid
        })
        logger.debug(f"ExotelOutboundPacer: Enqueued turn_end sentinel (turn_id={tid}) for stream: {self.stream_sid}")

    async def enqueue_audio(self, ulaw_data: bytes, metadata: Optional[dict] = None):
        """
        Accept μ-law audio bytes (e.g. from ElevenLabs TTS), convert to 16-bit linear PCM
        (8kHz mono), chunk into 320-byte 20ms frames, and enqueue.
        """
        # Convert μ-law to 16-bit linear PCM
        pcm_data = ulaw_to_pcm(ulaw_data)
        total_len = len(pcm_data)

        for offset in range(0, total_len, PCM_BYTES_PER_FRAME):
            frame = pcm_data[offset:offset + PCM_BYTES_PER_FRAME]
            # Pad with PCM silence if needed to exactly 320 bytes
            if len(frame) < PCM_BYTES_PER_FRAME:
                frame = frame + b"\x00" * (PCM_BYTES_PER_FRAME - len(frame))

            is_last = (offset + PCM_BYTES_PER_FRAME >= total_len)
            await self._queue.put({
                "type": "audio",
                "data": frame,
                "metadata": metadata,
                "is_last": is_last
            })

    def handle_mark_ack(self, mark_name: str):
        """Called when Exotel sends back a 'mark' event acknowledgment."""
        self._last_acked_mark = mark_name
        if mark_name in self._sent_marks:
            self._last_acked_metadata = self._sent_marks[mark_name]
        logger.debug(f"ExotelOutboundPacer: ACK received for mark: {mark_name}")

    def get_last_acked(self) -> tuple[Optional[str], Optional[dict]]:
        """Return the last acknowledged mark and its associated metadata."""
        return self._last_acked_mark, self._last_acked_metadata

    async def flush(self):
        """
        Immediately clear all queued audio frames and send Exotel 'clear' event.
        Used for sub-200ms barge-in interruption.
        """
        self._active_turn_id += 1
        self._turn_final_mark_sent = False
        self._frames_since_mark = 0
        dropped_frames = 0
        while not self._queue.empty():
            try:
                self._queue.get_nowait()
                self._queue.task_done()
                dropped_frames += 1
            except (asyncio.QueueEmpty, ValueError):
                break

        # Send Exotel clear event to immediately purge Exotel's internal playback buffer
        clear_message = json.dumps({
            "event": "clear",
            "stream_sid": self.stream_sid,
            "streamSid": self.stream_sid
        })
        try:
            await self.send_fn(clear_message)
            logger.info(
                f"ExotelOutboundPacer flushed {dropped_frames} frames & sent CLEAR for stream: {self.stream_sid}"
            )
        except Exception as exc:
            logger.error(f"Failed to send Exotel clear event: {exc}")

    async def stop(self):
        """Stop pacer and cleanup background task."""
        self._running = False
        if self._pacer_task and not self._pacer_task.done():
            self._pacer_task.cancel()
            try:
                await self._pacer_task
            except asyncio.CancelledError:
                pass
        logger.info(f"ExotelOutboundPacer stopped for stream: {self.stream_sid}")

    async def _pacing_loop(self):
        """Core loop sending 20ms linear16 PCM frames at 50Hz with precise timing."""
        next_deadline = time.monotonic()

        while self._running:
            try:
                item = await self._queue.get()
                if item is None:
                    break

                if item["type"] == "audio":
                    frame_bytes = item["data"]
                    metadata = item.get("metadata") or {}
                    is_last = item.get("is_last", False)

                    # Encode linear16 PCM to Base64
                    payload = base64.b64encode(frame_bytes).decode("ascii")
                    media_message = json.dumps({
                        "event": "media",
                        "stream_sid": self.stream_sid,
                        "streamSid": self.stream_sid,
                        "media": {
                            "payload": payload
                        }
                    })
                    await self.send_fn(media_message)
                    self._frames_since_mark += 1

                    # Check if next item in queue is turn_end sentinel
                    is_turn_end_next = False
                    if not self._queue.empty():
                        next_item = self._queue._queue[0]
                        if (
                            next_item is not None
                            and next_item.get("type") == "turn_end"
                            and next_item.get("turn_id") == self._active_turn_id
                        ):
                            is_turn_end_next = True

                    self._last_audio_metadata = metadata
                    if self._frames_since_mark >= self.mark_interval_frames or is_last:
                        self._mark_counter += 1
                        mark_name = f"exotel_mark_{self._mark_counter}"
                        is_final = bool(is_last and is_turn_end_next)
                        if is_final:
                            self._turn_final_mark_sent = True

                        self._sent_marks[mark_name] = {
                            **metadata,
                            "frame_count": self._frames_since_mark,
                            "is_last": is_last,
                            "is_final": is_final,
                            "sent_at": time.time()
                        }
                        mark_payload = {
                            "name": mark_name,
                            "is_last": is_last,
                            "is_final": is_final
                        }
                        if metadata.get("text"):
                            mark_payload["text"] = metadata["text"]
                        if metadata.get("tool_result"):
                            mark_payload["tool_result"] = metadata["tool_result"]

                        mark_msg = json.dumps({
                            "event": "mark",
                            "stream_sid": self.stream_sid,
                            "streamSid": self.stream_sid,
                            "mark": mark_payload
                        })
                        await self.send_fn(mark_msg)
                        self._frames_since_mark = 0

                        if is_final and self.on_playback_complete:
                            self.on_playback_complete()

                elif item["type"] == "turn_end":
                    sentinel_turn_id = item.get("turn_id")
                    if sentinel_turn_id != self._active_turn_id:
                        logger.debug(
                            f"ExotelOutboundPacer: Ignored stale turn_end sentinel (turn_id={sentinel_turn_id})"
                        )
                    else:
                        if not self._turn_final_mark_sent:
                            self._mark_counter += 1
                            mark_name = f"exotel_mark_{self._mark_counter}"
                            self._sent_marks[mark_name] = {
                                "frame_count": self._frames_since_mark,
                                "is_last": True,
                                "is_final": True,
                                "sent_at": time.time()
                            }
                            mark_payload = {
                                "name": mark_name,
                                "is_last": True,
                                "is_final": True
                            }
                            last_meta = getattr(self, "_last_audio_metadata", None)
                            if last_meta and last_meta.get("text"):
                                mark_payload["text"] = last_meta["text"]
                            if last_meta and last_meta.get("tool_result"):
                                mark_payload["tool_result"] = last_meta["tool_result"]

                            mark_msg = json.dumps({
                                "event": "mark",
                                "stream_sid": self.stream_sid,
                                "streamSid": self.stream_sid,
                                "mark": mark_payload
                            })
                            await self.send_fn(mark_msg)
                            self._frames_since_mark = 0
                            if self.on_playback_complete:
                                self.on_playback_complete()

                        self._turn_final_mark_sent = False

                self._queue.task_done()

                # Pace at 50Hz (20ms interval)
                next_deadline += self.frame_interval_sec
                delay = next_deadline - time.monotonic()
                if delay > 0:
                    await asyncio.sleep(delay)
                else:
                    next_deadline = time.monotonic()

            except asyncio.CancelledError:
                break
            except Exception as exc:
                logger.error(f"Exception in Exotel pacing loop: {exc}")
                await asyncio.sleep(0.01)


class ExotelMediaAdapter:
    """
    Exotel-specific audio and event adapter.
    Adapts bidirectional Exotel AgentStream 8kHz linear16 PCM audio and events
    to the internal voice pipeline (AssemblyAI STT, EnergyGate, VoiceAgentOrchestrator).

    Flow:
    Exotel Inbound (8kHz mono PCM16)
        -> Decode Base64
        -> Buffer & Slice into 320-byte 20ms frames
        -> Convert to G.711 μ-law (160 bytes)
        -> EnergyGate (interruption / barge-in detection)
        -> AssemblyAI STT (v3 streaming WebSocket)
    """

    def __init__(
        self,
        stream_sid: str,
        pacer: ExotelOutboundPacer,
        orchestrator=None,
        stt=None,
    ):
        self.stream_sid = stream_sid
        self.pacer = pacer
        self.orchestrator = orchestrator
        self.stt = stt
        self._inbound_pcm_buffer = bytearray()

    def set_pipeline_components(self, orchestrator, stt):
        """Bind active orchestrator and STT instances."""
        self.orchestrator = orchestrator
        self.stt = stt

    async def handle_inbound_media_payload(self, payload_b64: str):
        """
        Process inbound audio payload from Exotel AgentStream 'media' event.
        Decodes base64 linear16 PCM audio, buffers into 20ms frames (320 bytes),
        converts each frame to μ-law (160 bytes), and routes to EnergyGate and STT.
        """
        if not payload_b64:
            return

        pcm_bytes = base64.b64decode(payload_b64)
        self._inbound_pcm_buffer.extend(pcm_bytes)

        # Process all complete 20ms frames (320 bytes of 16-bit linear PCM at 8kHz)
        while len(self._inbound_pcm_buffer) >= PCM_BYTES_PER_FRAME:
            pcm_frame = bytes(self._inbound_pcm_buffer[:PCM_BYTES_PER_FRAME])
            del self._inbound_pcm_buffer[:PCM_BYTES_PER_FRAME]

            # Convert 320 bytes PCM16 to 160 bytes μ-law for EnergyGate & AssemblyAI STT
            ulaw_frame = pcm_to_ulaw(pcm_frame)

            # Route to EnergyGate for barge-in voice onset detection
            if self.orchestrator:
                await self.orchestrator.handle_inbound_audio(ulaw_frame)

            # Route to AssemblyAI STT
            if self.stt:
                await self.stt.send_audio(ulaw_frame)

    def handle_mark_event(self, mark_data: dict):
        """Handle incoming 'mark' event from Exotel."""
        mark_name = mark_data.get("name") if isinstance(mark_data, dict) else str(mark_data)
        if mark_name and self.pacer:
            self.pacer.handle_mark_ack(mark_name)

    def handle_clear_event(self):
        """Handle incoming 'clear' event from Exotel."""
        self._inbound_pcm_buffer.clear()
        logger.debug(f"ExotelMediaAdapter: Inbound buffer cleared for stream: {self.stream_sid}")
