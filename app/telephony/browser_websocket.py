class BrowserOutboundPacer:
    """
    Outbound audio pacer tailored for browser WebSocket clients.
    Converts μ-law audio generated by ElevenLabs TTS into 16-bit linear PCM (8kHz mono),
    paces audio frames (~20ms per packet), tracks mark events, and handles sub-200ms
    barge-in interruption by immediately flushing the outbound queue and dispatching
    a 'clear' event to stop browser audio playback instantly.
    """

    def __init__(
        self,
        stream_sid: str,
        send_fn: Callable[[str], Coroutine],
        frame_interval_sec: float = 0.02,
        mark_interval_frames: int = 15,
        on_playback_complete: Optional[Callable[[], None]] = None,
    ):
        self.stream_sid = stream_sid
        self.send_fn = send_fn
        self.frame_interval_sec = frame_interval_sec
        self.mark_interval_frames = mark_interval_frames
        self.on_playback_complete = on_playback_complete

        self._queue: asyncio.Queue[Optional[dict]] = asyncio.Queue()
        self._pacer_task: Optional[asyncio.Task] = None
        self._running = False

        self._mark_counter = 0
        self._sent_marks: Dict[str, dict] = {}
        self._last_acked_mark: Optional[str] = None
        self._last_acked_metadata: Optional[dict] = None
        self._frames_since_mark = 0
        self._turn_final_mark_sent = False
        self._active_turn_id = 1
        self._frame_seq = 0
        self._last_audio_metadata: Optional[dict] = None
        self._last_enqueued_metadata: Optional[dict] = None
        self._pcm_buffer = bytearray()

    def start(self):
        """Start background audio pacing loop."""
        if not self._running:
            self._running = True
            self._pacer_task = asyncio.create_task(self._pacing_loop())
            logger.info(f"BrowserOutboundPacer started for stream: {self.stream_sid}")

    def start_turn(self) -> int:
        """Begin new assistant turn, advancing turn generation."""
        self._active_turn_id += 1
        self._turn_final_mark_sent = False
        self._last_enqueued_metadata = None
        self._pcm_buffer.clear()
        self._frame_seq = 0
        return self._active_turn_id

    def mark_turn_end(self, turn_id: Optional[int] = None):
        """
        Signal that all audio chunks for the current assistant turn have been enqueued.
        Pads any leftover trailing partial frame with silence only at the very end of the turn.
        """
        tid = self._active_turn_id if turn_id is None else turn_id
        if self._pcm_buffer:
            pad_len = PCM_BYTES_PER_FRAME - len(self._pcm_buffer)
            final_frame = bytes(self._pcm_buffer) + (b"\x00" * pad_len)
            self._pcm_buffer.clear()
            self._queue.put_nowait({
                "type": "audio",
                "data": final_frame,
                "metadata": self._last_enqueued_metadata or self._last_audio_metadata,
                "is_last": True
            })

        self._queue.put_nowait({
            "type": "turn_end",
            "turn_id": tid
        })
        logger.debug(f"BrowserOutboundPacer: Enqueued turn_end sentinel (turn_id={tid}) for stream: {self.stream_sid}")

    async def enqueue_audio(self, ulaw_data: bytes, metadata: Optional[dict] = None):
        """
        Accept μ-law audio bytes, convert to 16-bit linear PCM (8kHz mono),
        accumulate in PCM buffer, and enqueue full 320-byte (20ms) frames without
        injecting premature silence padding mid-stream.
        """
        if not ulaw_data:
            return
        if metadata:
            self._last_enqueued_metadata = metadata
        pcm_data = ulaw_to_pcm(ulaw_data)
        self._pcm_buffer.extend(pcm_data)

        while len(self._pcm_buffer) >= PCM_BYTES_PER_FRAME:
            frame = bytes(self._pcm_buffer[:PCM_BYTES_PER_FRAME])
            del self._pcm_buffer[:PCM_BYTES_PER_FRAME]

            await self._queue.put({
                "type": "audio",
                "data": frame,
                "metadata": metadata,
                "is_last": False
            })

    def handle_mark_ack(self, mark_name: str):
        """Handle acknowledged mark from browser playback."""
        self._last_acked_mark = mark_name
        if mark_name in self._sent_marks:
            self._last_acked_metadata = self._sent_marks[mark_name]
        logger.debug(f"BrowserPacer: ACK received for mark: {mark_name}")

    def get_last_acked(self) -> tuple[Optional[str], Optional[dict]]:
        """Return the last acknowledged mark and associated metadata."""
        return self._last_acked_mark, self._last_acked_metadata

    async def flush(self):
        """Immediately clear all queued audio frames and send 'clear' event to browser."""
        self._pcm_buffer.clear()
        flushed_count = 0
        while not self._queue.empty():
            try:
                item = self._queue.get_nowait()
                self._queue.task_done()
                if item and item.get("type") == "audio":
                    flushed_count += 1
            except (asyncio.QueueEmpty, ValueError):
                break

        logger.info(f"BrowserOutboundPacer: Flushed {flushed_count} queued audio frames on barge-in.")

        clear_msg = json.dumps({
            "event": "clear",
            "stream_sid": self.stream_sid
        })
        await self.send_fn(clear_msg)

    async def reset(self):
        """Flush audio queue and reset all mark tracking state."""
        self._pcm_buffer.clear()
        await self.flush()
        self._sent_marks.clear()
        self._last_acked_mark = None
        self._last_acked_metadata = None
        self._frames_since_mark = 0
        self._turn_final_mark_sent = False
        self._active_turn_id = 1
        self._frame_seq = 0
        self._last_audio_metadata = None
        self._last_enqueued_metadata = None
        self._last_sent_text = None

    async def stop(self):
        """Stop background pacer task."""
        self._running = False
        self._pcm_buffer.clear()
        if self._pacer_task and not self._pacer_task.done():
            self._pacer_task.cancel()
            try:
                await self._pacer_task
            except asyncio.CancelledError:
                pass
        logger.info(f"BrowserOutboundPacer stopped for stream: {self.stream_sid}")

    async def _pacing_loop(self):
        """Main loop pacing audio frames at precise 20ms intervals with drift compensation."""
        next_deadline = time.monotonic()
        while self._running:
            try:
                item = await self._queue.get()
                if item is None:
                    break

                item_type = item.get("type")

                if item_type == "turn_end":
                    turn_id = item.get("turn_id", self._active_turn_id)
                    self._last_sent_text = None
                    if turn_id == self._active_turn_id and not self._turn_final_mark_sent:
                        self._turn_final_mark_sent = True
                        final_mark_name = f"browser_turn_end_{self.stream_sid}_{turn_id}_{int(time.monotonic() * 1000)}"
                        self._sent_marks[final_mark_name] = self._last_audio_metadata or {"type": "turn_final"}
                        final_mark_msg = json.dumps({
                            "event": "mark",
                            "stream_sid": self.stream_sid,
                            "mark": {"name": final_mark_name}
                        })
                        await self.send_fn(final_mark_msg)
                        if self.on_playback_complete:
                            self.on_playback_complete()
                    self._queue.task_done()
                    next_deadline = time.monotonic()
                    continue

                if item_type == "audio":
                    pcm_frame = item.get("data")
                    meta = item.get("metadata")
                    if meta:
                        self._last_audio_metadata = meta
                        sent_text = meta.get("text")
                        if sent_text:
                            self._last_sent_text = sent_text

                    if pcm_frame:
                        self._frame_seq += 1
                        payload_b64 = base64.b64encode(pcm_frame).decode("ascii")
                        media_msg = json.dumps({
                            "event": "media",
                            "stream_sid": self.stream_sid,
                            "media": {
                                "payload": payload_b64
                            },
                            "format": "pcm16_8000",
                            "seq": self._frame_seq,
                            "turn_id": f"asst_{self._active_turn_id}"
                        })
                        await self.send_fn(media_msg)

                        self._frames_since_mark += 1
                        if self._frames_since_mark >= self.mark_interval_frames:
                            self._mark_counter += 1
                            mark_name = f"browser_mark_{self.stream_sid}_{self._mark_counter}"
                            self._sent_marks[mark_name] = meta or {}
                            self._frames_since_mark = 0

                            mark_msg = json.dumps({
                                "event": "mark",
                                "stream_sid": self.stream_sid,
                                "mark": {"name": mark_name}
                            })
                            await self.send_fn(mark_msg)

                    self._queue.task_done()

                    # Precise drift-compensated frame pacing (20ms)
                    now = time.monotonic()
                    if next_deadline < now - 0.1:
                        next_deadline = now
                    next_deadline += self.frame_interval_sec
                    delay = next_deadline - time.monotonic()
                    if delay > 0:
                        await asyncio.sleep(delay)

            except asyncio.CancelledError:
                break
            except Exception as e:
                logger.error(f"Error in BrowserOutboundPacer loop: {e}", exc_info=True)
                await asyncio.sleep(self.frame_interval_sec)


# In-memory registry of active browser voice sessions for coordinated global resets
_ACTIVE_BROWSER_SESSIONS: Dict[str, Dict[str, Any]] = {}


async def clear_active_browser_sessions():
    """
    Completely reset all active browser voice sessions:
    cancels pending LLM streaming and TTS synthesis, flushes outbound pacers,
    resets SessionState context and messages, and notifies connected clients.
    """
    logger.info(f"Clearing {len(_ACTIVE_BROWSER_SESSIONS)} active browser voice session(s)")
    for sid, sess in list(_ACTIVE_BROWSER_SESSIONS.items()):
        try:
            orch = sess.get("orchestrator")
            if orch and hasattr(orch, "reset_conversation"):
                await orch.reset_conversation()
            stt_prov = sess.get("stt")
            if stt_prov and hasattr(stt_prov, "reset"):
                stt_prov.reset()
            pacer_inst = sess.get("pacer")
            if pacer_inst and hasattr(pacer_inst, "reset"):
                await pacer_inst.reset()
            ws_inst = sess.get("websocket")
            if ws_inst:
                try:
                    await ws_inst.send_text(json.dumps({
                        "event": "conversation_cleared",
                        "session_id": sid,
                        "state": "LISTENING"
                    }))
                except Exception:
                    pass
        except Exception as e:
            logger.debug(f"Error resetting active browser session {sid}: {e}")


@browser_router.websocket("/ws/browser-voice")
async def browser_voice_ws(websocket: WebSocket):

    """
    Dedicated production WebSocket endpoint for Browser Voice Conversations.
    Handles microphone audio streaming, two-way speech, real-time barge-in,
    and live synchronized tool & RAG state visualization.
    """
    await websocket.accept()
    logger.info("WebSocket connection established for Browser Voice.")

    session_id: str = f"browser_{int(time.time() * 1000)}"
    stream_sid: str = session_id
    call_sid: str = session_id

    orchestrator: Optional[VoiceAgentOrchestrator] = None
    pacer: Optional[BrowserOutboundPacer] = None
    stt: Optional[STTProvider] = None

    async def send_to_browser(message_str: str):
        try:
            await websocket.send_text(message_str)
        except Exception as err:
            logger.debug(f"Error sending message to browser voice WS: {err}")

    # Send initial connection confirmation
    await websocket.send_text(json.dumps({
        "event": "connected",
        "session_id": session_id,
        "state": "IDLE"
    }))

    try:
        while True:
            # Handle text messages (JSON) or binary audio frames
            ws_message = await websocket.receive()
            msg_type = ws_message.get("type")

            if msg_type == "websocket.disconnect":
                break

            data = {}
            binary_data = None

            if "bytes" in ws_message and ws_message["bytes"]:
                binary_data = ws_message["bytes"]
            elif "text" in ws_message and ws_message["text"]:
                try:
                    data = json.loads(ws_message["text"])
                except Exception:
                    data = {}

            event_type = data.get("event")

            # 1. Start Voice Session
            if event_type == "start":
                client_session_id = data.get("session_id")
                if client_session_id:
                    session_id = client_session_id
                    stream_sid = session_id
                    call_sid = session_id

                logger.info(f"Browser Voice session starting: {session_id}")

                # Notify global dashboard event bus
                try:
                    await event_broadcaster.notify_call_started(
                        call_sid=call_sid,
                        stream_sid=stream_sid,
                        caller_number="Browser Voice (Recruiter Demo)"
                    )
                except Exception as b_err:
                    logger.debug(f"Broadcaster notification error: {b_err}")

                # Initialize Browser Outbound Pacer
                pacer = BrowserOutboundPacer(
                    stream_sid=stream_sid,
                    send_fn=send_to_browser
                )
                pacer.start()

                # Initialize Voice Agent Orchestrator
                from app.tts.elevenlabs import ElevenLabsTTSProvider
                is_simulated = (
                    bool(data.get("simulated"))
                    or bool(data.get("offline"))
                    or session_id.startswith("test_")
                    or session_id.startswith("recruiter_")
                )
                tts_inst = ElevenLabsTTSProvider(api_key="") if is_simulated else ElevenLabsTTSProvider()
                orchestrator = VoiceAgentOrchestrator(
                    call_sid=call_sid,
                    stream_sid=stream_sid,
                    pacer=pacer,
                    tts_provider=tts_inst
                )
                pacer.on_playback_complete = orchestrator.turn_manager.on_tts_finished

                # Initialize Streaming STT
                async def on_stt_interim(text: str):
                    tid = orchestrator.turn_manager.current_user_turn_id or orchestrator.turn_manager.start_user_turn()
                    await orchestrator.handle_interim_transcript(text, turn_id=tid)
                    await send_to_browser(json.dumps({
                        "event": "transcript",
                        "role": "user",
                        "content": text,
                        "turn_id": tid,
                        "is_final": False
                    }))

                async def on_stt_final(text: str):
                    tid = orchestrator.turn_manager.current_user_turn_id
                    committed = await orchestrator.handle_final_transcript(text, turn_id=tid)
                    if committed:
                        final_tid = orchestrator.turn_manager.last_committed_turn_id or tid
                        await send_to_browser(json.dumps({
                            "event": "transcript",
                            "role": "user",
                            "content": text,
                            "turn_id": final_tid,
                            "is_final": True
                        }))
                    else:
                        logger.info(f"TURN DUPLICATE IGNORED: {tid or 'browser_ws'}")

                stt_callbacks = STTCallback(
                    on_interim=on_stt_interim,
                    on_final=on_stt_final,
                    on_error=lambda err: logger.error(f"Browser STT error: {err}")
                )
                stt = get_stt_provider(callbacks=stt_callbacks, simulated_utterance="simulated" if is_simulated else None)
                try:
                    await stt.connect()
                except Exception as stt_err:
                    logger.warning(f"Browser STT connect warning: {stt_err}")

                # Register active session in global registry for coordinated clear actions
                _ACTIVE_BROWSER_SESSIONS[session_id] = {
                    "orchestrator": orchestrator,
                    "pacer": pacer,
                    "stt": stt,
                    "websocket": websocket,
                }

                # Notify browser that session is ready

                await send_to_browser(json.dumps({
                    "event": "session_state",
                    "state": "LISTENING"
                }))

                # Deliver initial spoken welcome greeting safely
                async def deliver_initial_greeting():
                    try:
                        await orchestrator.send_initial_greeting()
                    except Exception as g_err:
                        logger.error(f"Error delivering initial greeting in browser voice: {g_err}")

                asyncio.create_task(deliver_initial_greeting())

            # 2. Inbound Microphone Audio Frame
            elif event_type == "media" or event_type == "audio" or binary_data is not None:
                if not orchestrator or not stt:
                    continue

                pcm_frame: Optional[bytes] = None
                if binary_data:
                    pcm_frame = binary_data
                else:
                    payload_b64 = (
                        data.get("media", {}).get("payload")
                        or data.get("data")
                        or data.get("payload")
                    )
                    if payload_b64:
                        pcm_frame = base64.b64decode(payload_b64)

                if pcm_frame:
                    audio_fmt = data.get("format", "pcm16_8000")
                    if audio_fmt in ("ulaw", "ulaw_8000"):
                        ulaw_data = pcm_frame
                    else:
                        ulaw_data = pcm_to_ulaw(pcm_frame)

                    # Feed exact 20ms frames to EnergyGate (VAD & barge-in) and STT
                    for chunk in chunk_audio(ulaw_data, ULAW_BYTES_PER_FRAME):
                        if len(chunk) == ULAW_BYTES_PER_FRAME:
                            await orchestrator.handle_inbound_audio(chunk)
                            if not orchestrator.turn_manager.is_speaking():
                                await stt.send_audio(chunk)

            # 3. Direct or UI Transcript Injection
            elif event_type == "transcript":
                if not orchestrator:
                    continue
                transcript_text = data.get("text", "").strip()
                is_final = data.get("is_final", False)
                turn_id = data.get("turn_id")
                if transcript_text:
                    if is_final:
                        await orchestrator.handle_final_transcript(transcript_text, turn_id=turn_id)
                    else:
                        await orchestrator.handle_interim_transcript(transcript_text, turn_id=turn_id)

            # 4. Browser-Initiated Barge-In Interruption
            elif event_type == "barge_in":
                if orchestrator:
                    logger.info(f"Browser voice client requested immediate barge-in for session: {session_id}")
                    await orchestrator._execute_barge_in()

            # 5. Playback Mark Acknowledgment
            elif event_type == "mark_ack" or event_type == "mark":
                mark_name = data.get("mark") or data.get("name")
                if mark_name and pacer:
                    pacer.handle_mark_ack(mark_name)

            # 6. Mute / Unmute state from UI
            elif event_type == "mute":
                is_muted = data.get("muted", False)
                logger.info(f"Browser voice session {session_id} muted={is_muted}")

            # 7. Ping / Heartbeat
            elif event_type == "ping":
                await send_to_browser(json.dumps({"event": "pong", "timestamp": time.time()}))

            # 8. Clear Active Conversation
            elif event_type == "clear_conversation":
                logger.info(f"Browser voice clear conversation requested for session: {session_id}")
                if orchestrator:
                    await orchestrator.reset_conversation()
                if stt and hasattr(stt, "reset"):
                    stt.reset()
                if pacer and hasattr(pacer, "reset"):
                    await pacer.reset()
                await event_broadcaster.clear_conversation()
                await send_to_browser(json.dumps({
                    "event": "conversation_cleared",
                    "session_id": session_id,
                    "state": "LISTENING"
                }))

            # 9. Stop Voice Conversation
            elif event_type == "stop":
                logger.info(f"Browser voice stop requested for session: {session_id}")
                break

    except WebSocketDisconnect:
        logger.info(f"Browser voice WebSocket disconnected for session: {session_id}")
    except Exception as exc:
        logger.error(f"Exception in browser voice WebSocket: {exc}", exc_info=True)
    finally:
        # Deregister active browser session
        _ACTIVE_BROWSER_SESSIONS.pop(session_id, None)

        # Graceful cleanup
        try:
            await event_broadcaster.notify_call_ended(call_sid=call_sid, stream_sid=stream_sid)
        except Exception:
            pass
        if pacer:
            await pacer.stop()
        if stt:
            await stt.close()
        logger.info(f"Cleaned up browser voice session: {session_id}")

